// Generates src/styles/type-tokens.css from design-system/tokens.json so app CSS can use
// `font: var(--type-label)` and `letter-spacing: var(--track-label)` instead of literal sizes.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('design-system/tokens.json', 'utf8'));
const lines = ['/* Generated by scripts/build-type-tokens.mjs from design-system/tokens.json. Do not edit. */', ':root {'];
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    lines.push(`  --type-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family ?? group.family});`);
    lines.push(`  --track-${s.name}: ${s.letterSpacing ?? 'normal'};`);
  }
}
lines.push('}', '');
writeFileSync('src/styles/type-tokens.css', lines.join('\n'));
console.log('wrote src/styles/type-tokens.css');
